package engine

import (
	"bufio"
	"errors"
	"io"
	"io/fs"
	"os"
	"regexp"
)

type (
	// GeneratePolicyFunc returns the GeneratePolicy of a Template,
	// given its output path (prefixed with the generation root directory) and the configuration.
	GeneratePolicyFunc[T any] func(path string, config T) GeneratePolicy

	// GeneratePolicy defines the policy for generating a given file.
	//
	// By default, the policy is set to PolicyDefault.
	GeneratePolicy int
)

const (
	// PolicyAlways generates the file on every run, even when it was edited by hand.
	//
	// Patches are applied afterwards.
	PolicyAlways GeneratePolicy = iota + 1

	// PolicyDefault generates the file when it's owned by generation (see IsGenerated) or when generation is forced (see WithForce).
	//
	// Otherwise, the existing file is kept and only its sections are regenerated.
	// Patches are applied in both cases.
	PolicyDefault

	// PolicyRemove removes the file (or directory) when it exists, instead of generating it.
	//
	// It applies even when generation is forced, and no sections or patches are applied.
	PolicyRemove

	// PolicySkip leaves the file untouched, whether it exists or not.
	//
	// It applies even when generation is forced, and no sections or patches are applied.
	PolicySkip
)

const notice = `Code generated by [\w\-\/]+; DO NOT EDIT\.`

// generated matches the notice opening one of the first 3 lines, only comment syntax allowed before it.
var generated = regexp.MustCompile(`^(?:.*\n){0,2}[^\w\n]*` + notice)

// IsGenerated returns true if out is owned by generation.
//
// A file is owned by generation if:
//   - the generated notice opens one of its first 3 lines
//   - it does not exist
//   - it is empty
func IsGenerated(out string) (bool, error) {
	file, err := os.Open(out)
	if err != nil {
		if errors.Is(err, fs.ErrNotExist) {
			return true, nil
		}
		return false, err
	}
	defer file.Close()

	// only the first 3 lines can hold the generated notice
	reader := bufio.NewReader(file)
	var head []byte
	for range 3 {
		line, err := reader.ReadBytes('\n')
		head = append(head, line...) // line is returned together with io.EOF in some cases
		if err != nil {
			if errors.Is(err, io.EOF) {
				break
			}
			return false, err
		}
	}
	return len(head) == 0 || generated.Match(head), nil
}

// StaticPolicy returns a GeneratePolicyFunc always returning the given policy,
// regardless of the output file path and configuration.
func StaticPolicy[T any](policy GeneratePolicy) GeneratePolicyFunc[T] {
	return func(string, T) GeneratePolicy {
		return policy
	}
}

// RemoveIf returns a GeneratePolicyFunc removing the output file when remove returns true, and applying otherwise in other cases.
func RemoveIf[T any](remove func(T) bool, otherwise GeneratePolicy) GeneratePolicyFunc[T] {
	return func(_ string, config T) GeneratePolicy {
		if remove(config) {
			return PolicyRemove
		}
		return otherwise
	}
}

// SkipIfExists returns PolicySkip when the path exists, and otherwise in other cases.
//
// It's meant to be called inside a GeneratePolicyFunc with its path,
// for files generated once and then left to the user.
//
// Unlike PolicyDefault, an existing file is kept even when generation is forced (see WithForce),
// with or without the generated notice.
func SkipIfExists(path string, otherwise GeneratePolicy) GeneratePolicy {
	if _, err := os.Lstat(path); err == nil {
		return PolicySkip
	}
	return otherwise
}

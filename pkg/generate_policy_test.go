package engine_test

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"

	engine "gitlab.com/kickr-dev/engine/pkg"
	"gitlab.com/kickr-dev/engine/pkg/files"
)

func TestIsGenerated(t *testing.T) {
	t.Run("generated_doesnt_exist", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "invalid.txt")

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.True(t, ok)
	})

	t.Run("not_generated_file", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("not generated"), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.False(t, ok)
	})

	t.Run("generated_folder", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "folder")
		require.NoError(t, os.Mkdir(dest, files.RwxRxRxRx))

		// Act
		_, err := engine.IsGenerated(dest)

		// Assert
		assert.Error(t, err)
	})

	t.Run("generated_no_lines", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		file, err := os.Create(dest)
		require.NoError(t, err)
		require.NoError(t, file.Close())

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.True(t, ok)
	})

	t.Run("generated_first_line", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("// Code generated by kickr; DO NOT EDIT."), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.True(t, ok)
	})

	t.Run("generated_md_comment", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("<!-- Code generated by kickr; DO NOT EDIT. -->"), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.True(t, ok)
	})

	t.Run("generated_second_line", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("\n# Code generated by kickr; DO NOT EDIT."), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.True(t, ok)
	})

	t.Run("generated_json", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte(`{
			"//": "Code generated by kickr; DO NOT EDIT.",
		}`), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.True(t, ok)
	})

	t.Run("generated_first_line_not_at_start", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("Files with `Code generated by kickr; DO NOT EDIT.` header"), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.False(t, ok)
	})

	t.Run("generated_second_line_not_at_start", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("# header\nFiles with `Code generated by kickr; DO NOT EDIT.` header"), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.False(t, ok)
	})

	t.Run("generated_after_third_line", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		err := os.WriteFile(dest, []byte("a\nb\nc\n# Code generated by kickr; DO NOT EDIT."), files.RwRR)
		require.NoError(t, err)

		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(t, err)
		assert.False(t, ok)
	})
}

func TestRemoveIf(t *testing.T) {
	policy := engine.RemoveIf(func(c testconfig) bool { return c.Str == "remove" }, engine.PolicyAlways)

	t.Run("success_remove", func(t *testing.T) {
		// Act
		actual := policy("file.txt", testconfig{Str: "remove"})

		// Assert
		assert.Equal(t, engine.PolicyRemove, actual)
	})

	t.Run("success_otherwise", func(t *testing.T) {
		// Act
		actual := policy("file.txt", testconfig{})

		// Assert
		assert.Equal(t, engine.PolicyAlways, actual)
	})
}

func TestSkipIfExists(t *testing.T) {
	t.Run("success_skip", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")
		require.NoError(t, os.WriteFile(dest, []byte("content"), files.RwRR))

		// Act
		actual := engine.SkipIfExists(dest, engine.PolicyAlways)

		// Assert
		assert.Equal(t, engine.PolicySkip, actual)
	})

	t.Run("success_otherwise", func(t *testing.T) {
		// Arrange
		dest := filepath.Join(t.TempDir(), "file.txt")

		// Act
		actual := engine.SkipIfExists(dest, engine.PolicyAlways)

		// Assert
		assert.Equal(t, engine.PolicyAlways, actual)
	})
}

func BenchmarkIsGenerated(b *testing.B) {
	// Arrange
	dest := filepath.Join(b.TempDir(), "file.txt")
	require.NoError(b, os.WriteFile(dest,
		[]byte("# Code generated by kickr; DO NOT EDIT.\n"+strings.Repeat("content\n", 128*1024)),
		files.RwRR))

	for b.Loop() {
		// Act
		ok, err := engine.IsGenerated(dest)

		// Assert
		require.NoError(b, err)
		assert.True(b, ok)
	}
}
